ALTER TABLE demo_users ADD COLUMN block_reason VARCHAR(500);
ALTER TABLE demo_users ADD COLUMN blocked_at TIMESTAMP WITH TIME ZONE;
CREATE TABLE recipe_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT NOT NULL REFERENCES demo_users(id),
    recipe_id BIGINT NOT NULL REFERENCES recipes(id),
    reason VARCHAR(32) NOT NULL CHECK (reason IN ('SPAM','ABUSE','COPYRIGHT','INCORRECT','OTHER')),
    description VARCHAR(1000) NOT NULL,
    status VARCHAR(24) NOT NULL CHECK (status IN ('OPEN','IN_REVIEW','RESOLVED','REJECTED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    moderator_id BIGINT REFERENCES demo_users(id),
    reviewed_at TIMESTAMP WITH TIME ZONE,
    moderator_comment VARCHAR(1000)
);
CREATE UNIQUE INDEX reports_active_unique ON recipe_reports(reporter_id, recipe_id, reason) WHERE status IN ('OPEN','IN_REVIEW');
CREATE INDEX reports_status_created ON recipe_reports(status, created_at DESC, id DESC);
CREATE INDEX reports_reporter_created ON recipe_reports(reporter_id, created_at DESC);
CREATE TABLE administrative_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id BIGINT NOT NULL REFERENCES demo_users(id),
    action VARCHAR(32) NOT NULL,
    target_type VARCHAR(32) NOT NULL,
    target_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    details VARCHAR(1000) NOT NULL
);
CREATE INDEX audit_action_created ON administrative_audit(action, created_at DESC, id DESC);
-- Keep reports and audit when a recipe is removed, retaining its identifier/title.
