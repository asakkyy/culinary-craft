CREATE TABLE demo_users (
    id BIGINT PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL CHECK (role IN ('USER', 'ADMIN')),
    initials VARCHAR(255) NOT NULL,
    subtitle VARCHAR(255) NOT NULL
);

CREATE TABLE recipes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    description VARCHAR(1500) NOT NULL,
    category VARCHAR(255) NOT NULL CHECK (category IN
        ('Завтраки', 'Основные блюда', 'Десерты', 'Салаты', 'Супы', 'Напитки')),
    emoji TEXT NOT NULL,
    image_url TEXT NOT NULL,
    prep_minutes INTEGER NOT NULL CHECK (prep_minutes BETWEEN 1 AND 1440),
    servings INTEGER NOT NULL CHECK (servings BETWEEN 1 AND 30),
    difficulty TEXT NOT NULL,
    owner_id BIGINT NOT NULL REFERENCES demo_users(id),
    status VARCHAR(255) NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX recipes_status_created_idx ON recipes(status, created_at DESC);
CREATE INDEX recipes_owner_idx ON recipes(owner_id);

CREATE TABLE recipe_ingredients (
    recipe_id BIGINT NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    position INTEGER NOT NULL CHECK (position >= 0),
    value TEXT NOT NULL,
    PRIMARY KEY (recipe_id, position)
);
CREATE TABLE recipe_steps (
    recipe_id BIGINT NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    position INTEGER NOT NULL CHECK (position >= 0),
    value TEXT NOT NULL,
    PRIMARY KEY (recipe_id, position)
);
CREATE TABLE recipe_tags (
    recipe_id BIGINT NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    position INTEGER NOT NULL CHECK (position >= 0),
    value TEXT NOT NULL,
    PRIMARY KEY (recipe_id, position)
);

CREATE TABLE reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
    recipe_id BIGINT NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL REFERENCES demo_users(id),
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment VARCHAR(500) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT reviews_recipe_author_unique UNIQUE (recipe_id, author_id)
);
CREATE INDEX reviews_recipe_created_idx ON reviews(recipe_id, created_at DESC, id DESC);

CREATE TABLE favorites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES demo_users(id),
    recipe_id BIGINT NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    CONSTRAINT favorites_user_recipe_unique UNIQUE (user_id, recipe_id)
);
CREATE INDEX favorites_recipe_idx ON favorites(recipe_id);
